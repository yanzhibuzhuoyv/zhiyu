package com.zhiyu.app.domain.planar

import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.security.MessageDigest
import org.junit.Assert.*
import org.junit.Test
import rig2d.planar.ParameterRange
import rig2d.planar.PlanarContract
import rig2d.planar.PlanarMixer
import rig2d.planar.PlanarParameters

class PlanarBasisFactoryTest {
    private val anchors = PlanarAnchors(PlanarPoint(47.75, 35.125), PlanarPoint(48.5, 81.75),
        PlanarRect(28.0, 33.0, 42.0, 41.0), PlanarRect(53.0, 33.0, 69.0, 41.0), PlanarRect(40.0, 53.0, 56.0, 60.0))

    @Test fun basisUsesDoubleUntilFinalFloatConversion() {
        val mesh = PlanarBasisFactory.create(intArrayOf(11, 7, 123, 89), "accessory", anchors,
            PlanarPoint(64.125, 35.75), .73, 157, 211, contract())
        // Expected hashes generated by studio/mesh.py, not by the Kotlin implementation.
        assertEquals("2e32d015c269a5145b4de398a20c99c53b34eea841530cf530bd7037ef70c74e", sha(mesh.baseVertices()))
        assertEquals("327e190b97b5f55572a35261e4b8c220584f6b0f3237ce41f102cec51d080ef2", sha(mesh.uv()))
        assertEquals("70dbdfbe44bce28f827ae58b11671b96b918a815a32e219729c101e2fd4f8285", sha(mesh.deltas().values.flatMap { it.toList() }.toFloatArray()))
    }

    @Test fun eyeBasisActuallyBlinksWithoutMovingRectangleBoundary() {
        val mesh = PlanarBasisFactory.create(intArrayOf(28, 33, 14, 8), "eye_left", anchors,
            anchors.head, 1.0, 157, 211, contract())
        val base = mesh.baseVertices()
        val mixed = PlanarMixer.vertices(mesh, PlanarParameters(mesh.contract, mapOf("blinkLeft" to 1f)))
        assertEquals(base[1], mixed[1], 0f)
        assertTrue(mixed.indices.any { mixed[it] != base[it] })
        assertEquals("b3583cbabee10077b56f5980c8b5e856fe927e9942037a5e73402bc1b0502f52", sha(mesh.deltas().values.flatMap { it.toList() }.toFloatArray()))
    }

    private fun sha(values: FloatArray): String {
        val buffer = ByteBuffer.allocate(values.size * 4).order(ByteOrder.LITTLE_ENDIAN)
        values.forEach { buffer.putFloat(it) }
        return MessageDigest.getInstance("SHA-256").digest(buffer.array()).joinToString("") { "%02x".format(it) }
    }

    private fun contract() = PlanarContract(1536, 1089, 2048, linkedMapOf(
        "headX" to ParameterRange(-1f, 1f, 0f), "headY" to ParameterRange(-1f, 1f, 0f),
        "tilt" to ParameterRange(-1f, 1f, 0f), "blinkLeft" to ParameterRange(0f, 1f, 0f),
        "blinkRight" to ParameterRange(0f, 1f, 0f), "mouth" to ParameterRange(0f, 1f, 0f),
        "breath" to ParameterRange(0f, 1f, 0f), "sway" to ParameterRange(-1f, 1f, 0f)))
}
