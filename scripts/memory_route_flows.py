def _long_question(prefix, suffix):
    filler = "我在记录今天看到的光影，只是当下片段，不包含过去那次活动的答案。"
    repeats = (15_900 - len(prefix) - len(suffix)) // len(filler)
    return prefix + filler * repeats + suffix


def _quoted(source):
    speaker = "你此前说" if source["role"] == "user" else "我此前承诺"
    return f"{speaker}：{source['text']}"


def _sources(spec, ordinal):
    return [
        {
            "id": f"{spec['id']}-old-{index}",
            "role": role,
            "created_at": f"2026-08-{ordinal + 1:02d}T0{index}:00:00+00:00",
            "text": text,
        }
        for index, (role, text) in enumerate(spec["seeds"], 1)
    ]


