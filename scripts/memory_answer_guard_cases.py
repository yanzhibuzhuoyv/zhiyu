def _make(
    case_id, category, subtype, pairs, query, expected, forbidden, expectation,
    good, bad, violation, reason, quotes=None, days=None,
):
    history = []
    days = days or ["2026-09-20"] * len(pairs)
    for number, (user, assistant) in enumerate(pairs, 1):
        for suffix, role, text, second in (
            ("u", "user", user, "00"), ("a", "assistant", assistant, "30")
        ):
            history.append({
                "id": f"{case_id}-{suffix}{number}", "role": role, "text": text,
                "created_at": f"{days[number - 1]}T09:{number:02d}:{second}+08:00",
            })
    originals = {item["id"]: item["text"] for item in history}
    expected_ids = [f"{case_id}-{suffix}" for suffix in expected]
    expected_quotes = (
        {key: originals[key] for key in expected_ids}
        if quotes is None else dict(zip(expected_ids, quotes, strict=True))
    )
    return {
        "id": case_id, "category": category, "subtype": subtype, "history": history,
        "query": query, "expected_ids": expected_ids, "expected_quotes": expected_quotes,
        "forbidden_ids": [f"{case_id}-{suffix}" for suffix in forbidden],
        "answer_expectation": expectation,
        "challenge_drafts": [
            {"id": f"{case_id}-safe", "text": good, "expected_supported": True,
             "violation": "none", "rationale": expectation},
            {"id": f"{case_id}-unsafe", "text": bad, "expected_supported": False,
             "violation": violation, "rationale": reason},
        ],
    }


