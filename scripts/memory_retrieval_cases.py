def _make(case_id, category, pairs, query, expected, forbidden, expectation, quotes=None):
    history = []
    for number, (user, assistant) in enumerate(pairs, 1):
        for suffix, role, text, second in (
            ("u", "user", user, "00"), ("a", "assistant", assistant, "30")
        ):
            history.append({
                "id": f"{case_id}-{suffix}{number}", "role": role, "text": text,
                "created_at": f"2026-09-12T09:{number:02d}:{second}+08:00",
            })
    originals = {item["id"]: item["text"] for item in history}
    expected_ids = [f"{case_id}-u{number}" for number in expected]
    expected_quotes = (
        {item: originals[item] for item in expected_ids}
        if quotes is None else dict(zip(expected_ids, quotes, strict=True))
    )
    return {
        "id": case_id, "category": category, "history": history, "query": query,
        "expected_ids": expected_ids,
        "forbidden_ids": [f"{case_id}-{suffix}" for suffix in forbidden],
        "answer_expectation": expectation, "expected_quotes": expected_quotes,
    }


